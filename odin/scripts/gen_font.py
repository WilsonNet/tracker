#!/usr/bin/env python3
"""Generate the embedded 8x14 bitmap font used by the native UI.

Run from odin/:  python3 scripts/gen_font.py
Requires Pillow and a monospace TTF. The generated file is committed so the
Odin build has no Python/font dependency.
"""
from PIL import Image, ImageDraw, ImageFont
import os

FONT_PATH = "/usr/share/fonts/noto/NotoSansMono-Regular.ttf"
FONT_SIZE = 12
W, H = 8, 14
FIRST, LAST = 32, 126
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "ui", "font_data.odin")

font = ImageFont.truetype(FONT_PATH, FONT_SIZE)
ascent, descent = font.getmetrics()

rows = []
for code in range(FIRST, LAST + 1):
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    ch = chr(code)
    # Center the glyph's inked box in the cell.
    bbox = d.textbbox((0, 0), ch, font=font)
    gw = bbox[2] - bbox[0]
    gh = bbox[3] - bbox[1]
    x = max(0, (W - gw) // 2 - bbox[0])
    y = max(0, (H - gh) // 2 - bbox[1])
    d.text((x, y), ch, fill=255, font=font)
    bits = []
    for yy in range(H):
        row = 0
        for xx in range(W):
            if img.getpixel((xx, yy)) >= 96:
                row |= 1 << (W - 1 - xx)
        bits.append(row)
    rows.append(bits)

with open(OUT, "w") as f:
    f.write("// Generated by scripts/gen_font.py from Noto Sans Mono 12px.\n")
    f.write("// 8x14 cells, ASCII 32..126, one u16 per row (MSB = leftmost pixel).\n\n")
    f.write("package ui\n\n")
    f.write(f"FONT_W :: {W}\n")
    f.write(f"FONT_H :: {H}\n")
    f.write(f"FONT_FIRST :: {FIRST}\n")
    f.write(f"FONT_LAST :: {LAST}\n\n")
    f.write("FONT_ROWS := [%d][%d]u16{\n" % (len(rows), H))
    for i, bits in enumerate(rows):
        ch = chr(FIRST + i)
        label = {"\\": "backslash", '"': "quote"}.get(ch, ch)
        f.write("\t{ " + ", ".join("0x%04x" % b for b in bits) + " }, // " + label + "\n")
    f.write("}\n")

print(f"wrote {OUT}: {len(rows)} glyphs, ascent={ascent} descent={descent}")
